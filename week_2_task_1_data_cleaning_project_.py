import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
import re

df = pd.read_csv("/content/india_job_market_2024_2026.csv")
df_before = df.copy()

print("Initial shape:", df.shape)
display(df.head())
df.info()
display(df.describe(include="all"))

"""# Missing values"""

display(pd.DataFrame({"Missing":df.isna().sum(),"Percentage":(df.isna().mean()*100).round(2)}))

plt.figure(figsize=(14,5))
sns.heatmap(df.isna(), cbar=False, yticklabels=False)
plt.title("Missing Values Heatmap")
plt.show()

"""# Standardize columns"""

df.columns = (df.columns.str.strip().str.lower()
              .str.replace(r"[^a-z0-9]+","_",regex=True).str.strip("_"))

"""# Text cleaning"""

for col in df.select_dtypes(include="object").columns:
    df[col] = df[col].apply(lambda x: re.sub(r"\\s+"," ",x).strip() if isinstance(x,str) else x)

"""# Types"""

if "job_id" in df: df["job_id"] = df["job_id"].astype("string")
for col in ["salary_lpa","openings","applicants","company_rating"]:
    if col in df: df[col] = pd.to_numeric(df[col],errors="coerce")
if "date_posted" in df: df["date_posted"] = pd.to_datetime(df["date_posted"],errors="coerce")

"""# Missing values"""

for col in df.columns:
    if df[col].isna().any():
        if pd.api.types.is_numeric_dtype(df[col]):
            df[col] = df[col].fillna(df[col].median())
        elif pd.api.types.is_datetime64_any_dtype(df[col]):
            vals=df[col].dropna().sort_values()
            if len(vals): df[col]=df[col].fillna(vals.iloc[len(vals)//2])
        else:
            m=df[col].mode(dropna=True)
            df[col]=df[col].fillna(m.iloc[0] if len(m) else "Unknown")

"""# Duplicates"""

print("Duplicates before:", df.duplicated().sum())
df=df.drop_duplicates().reset_index(drop=True)
print("Duplicates after:", df.duplicated().sum())

"""# IQR"""

for col in ["salary_lpa","openings","applicants","company_rating"]:
    if col in df:
        q1,q3=df[col].quantile(.25),df[col].quantile(.75)
        iqr=q3-q1
        lo,hi=q1-1.5*iqr,q3+1.5*iqr
        df[col+"_outlier"]=(df[col]<lo)|(df[col]>hi)
        print(col, "lower:",lo,"upper:",hi,"outliers:",int(df[col+"_outlier"].sum()))

"""# Boxplots"""

for col in ["salary_lpa","openings","applicants","company_rating"]:
    if col in df:
        plt.figure(figsize=(9,5))
        sns.boxplot(x=df[col])
        plt.title("Box Plot - "+col)
        plt.show()

"""# One-hot encoded copy"""

encoding_cols=[c for c in ["company_type","industry","location_tier","experience_level","job_type","work_mode","education_required"] if c in df]
df_encoded=pd.get_dummies(df,columns=encoding_cols,drop_first=True,dtype=int)

"""# Validation"""

print("Final shape:",df.shape)
print("Missing:",int(df.isna().sum().sum()))
print("Duplicates:",int(df.duplicated().sum()))
display(df.dtypes)
display(df.describe())

"""# Export"""

df.to_csv("/content/india_job_market_2024_2026.csv",index=False)
df_encoded.to_csv("/content/india_job_market_2024_2026.csv",index=False)
print("Files exported.")